'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const root = __dirname;
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

const layout = read('src/layout.html');
const header = read('src/partials/header.html');
const footer = read('src/partials/footer.html');
const player = read('src/partials/player.html');
const structuredData = read('src/partials/structured-data.html');
const site = JSON.parse(read('site.json'));
const siteUrl = String(site.siteUrl || '').replace(/\/+$/, '');

const assetHash = crypto.createHash('sha1');
for (const dir of ['assets/css', 'assets/js']) {
  for (const file of fs.readdirSync(path.join(root, dir)).sort()) {
    assetHash.update(file);
    assetHash.update(fs.readFileSync(path.join(root, dir, file)));
  }
}
const assetVersion = assetHash.digest('hex').slice(0, 8);

function parseFrontMatter(source) {
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) throw new Error('Page is missing front matter');
  const meta = {};
  for (const line of match[1].split(/\r?\n/)) {
    const idx = line.indexOf(':');
    if (idx === -1) continue;
    meta[line.slice(0, idx).trim()] = line.slice(idx + 1).trim();
  }
  return { meta, body: source.slice(match[0].length) };
}

function escapeAttr(value) {
  return String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
}

const pages = fs
  .readdirSync(path.join(root, 'src', 'pages'))
  .filter((file) => file.endsWith('.html'))
  .sort();

const built = [];

for (const file of pages) {
  const source = read(path.join('src', 'pages', file));
  const { meta, body } = parseFrontMatter(source);
  const name = path.basename(file, '.html');
  const pagePath = name === 'index' ? '/' : `/${name}.html`;
  if (!meta.title || !meta.description) throw new Error(`${file} needs a title and description`);
  if (!meta.page) throw new Error(`${file} needs a page id`);

  // 404.html answers unknown paths, so it must not claim a canonical URL of its own.
  // A noindex page is a station tool, not a published page: no canonical, no sitemap
  // entry and no structured data.
  const isPrivate = meta.noindex === 'true';
  const shareable = name !== '404' && !isPrivate;
  const absolute = siteUrl && shareable ? `${siteUrl}${pagePath}` : '';
  const canonical = absolute ? `<link rel="canonical" href="${escapeAttr(absolute)}">` : '';
  const ogUrl = absolute ? `<meta property="og:url" content="${escapeAttr(absolute)}">` : '';
  const ogImage = absolute
    ? `<meta property="og:image" content="${escapeAttr(`${siteUrl}/assets/images/hero-studio-1200.jpg`)}">`
    : '';
  const robots = isPrivate ? '<meta name="robots" content="noindex, nofollow">' : '';

  const pageHeader = header.replaceAll(`data-nav="${meta.page}"`, `data-nav="${meta.page}" aria-current="page"`);

  const html = layout
    .replaceAll('{{TITLE}}', meta.title)
    .replaceAll('{{DESCRIPTION}}', meta.description)
    .replaceAll('{{PAGE}}', meta.page)
    .replaceAll('{{BODY_CLASS}}', meta.bodyClass || '')
    .replaceAll('{{ROBOTS}}', robots)
    .replaceAll('{{CANONICAL}}', canonical)
    .replaceAll('{{OG_URL}}', ogUrl)
    .replaceAll('{{OG_IMAGE}}', ogImage)
    .replaceAll('{{STRUCTURED_DATA}}', isPrivate ? '' : structuredData)
    .replaceAll('{{HEADER}}', pageHeader)
    .replaceAll('{{FOOTER}}', footer)
    .replaceAll('{{PLAYER}}', player)
    .replaceAll('{{CONTENT}}', body.trim());

  const versioned = html.replace(/\b(assets\/(?:css|js)\/[A-Za-z0-9._-]+)(?!\?)/g, `$1?v=${assetVersion}`);
  fs.writeFileSync(path.join(root, file), `${versioned.trim()}\n`);
  if (name !== '404' && !isPrivate) built.push({ name, pagePath });
  console.log(`built ${file}${isPrivate ? ' (noindex, out of the sitemap)' : ''}`);
}

const robots = ['User-agent: *', 'Allow: /', '', `# Generated by build.js on ${new Date().toISOString().slice(0, 10)}`];
if (siteUrl) {
  robots.push(`Sitemap: ${siteUrl}/sitemap.xml`);
} else {
  robots.push('# Set site.siteUrl and rebuild to publish an absolute sitemap.');
}
robots.push('');
fs.writeFileSync(path.join(root, 'robots.txt'), robots.join('\n'));

const sitemapPath = path.join(root, 'sitemap.xml');
if (siteUrl) {
  const today = new Date().toISOString().slice(0, 10);
  const entries = built
    .map(
      ({ pagePath }) =>
        `  <url>\n    <loc>${escapeAttr(`${siteUrl}${pagePath}`)}</loc>\n    <lastmod>${today}</lastmod>\n  </url>`
    )
    .join('\n');
  fs.writeFileSync(
    sitemapPath,
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries}\n</urlset>\n`
  );
  console.log(`built sitemap.xml (${built.length} pages)`);
} else {
  if (fs.existsSync(sitemapPath)) fs.rmSync(sitemapPath);
  console.log('sitemap.xml skipped: set site.json siteUrl first');
}

console.log(`done: ${built.length} pages${siteUrl ? ` at ${siteUrl}` : ''}`);
